package fit.biejk.core.entity;

/**
 * Enumeration representing possible statuses of an order bid.
 */
public enum BidStatus {

    /**
     * Initial status when a bid is created.
     */
    CREATED,

    /**
     * Status indicating the bid has been approved.
     */
    APPROVED,

    /**
     * Status indicating the bid has been rejected.
     */
    REJECTED
}
