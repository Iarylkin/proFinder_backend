package fit.biejk.entity;

/**
 * Enumeration representing possible statuses of an order response.
 */
public enum OrderResponseStatus {

    /**
     * Initial status when a response is created.
     */
    CREATED,

    /**
     * Status indicating the response has been approved.
     */
    APPROVED,

    /**
     * Status indicating the response has been rejected.
     */
    REJECTED
}
